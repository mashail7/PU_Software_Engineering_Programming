public class PrintNumbers {

    public static void main(String[] args) {
        int i = 1;
        do {
            if (i % 2 == 0) {
                System.out.println(i + " chetno");
                i++;
            }
            else {
                System.out.println(i + " chetno");
                i++;
            }
        }while (i <= 10);
    }
}
